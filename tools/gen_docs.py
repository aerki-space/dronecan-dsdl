#!/usr/bin/env python3
"""Generate docs/types.md from the DSDL sources.

    python3 tools/gen_docs.py           # rewrite docs/types.md
    python3 tools/gen_docs.py --check   # exit 1 if docs/types.md is out of date (used in CI)
"""
import os
import sys

import validate

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'docs', 'types.md')


def render(types):
    lines = ['# Data types', '', 'Generated by `tools/gen_docs.py` from the files in `aerki/`. Do not edit by hand.', '',
             '| Type | Kind | ID | Max size | Signature |', '|---|---|---|---|---|']
    for t in types:
        if t.kind == t.KIND_SERVICE:
            kind, size = 'service', (f'req {validate.size_bytes(t.get_max_bitlen_request())} B / '
                                      f'resp {validate.size_bytes(t.get_max_bitlen_response())} B')
        else:
            kind, size = ('message' if t.default_dtid is not None else 'nested'), f'{validate.size_bytes(t.get_max_bitlen())} B'
        dtid = t.default_dtid if t.default_dtid is not None else '–'
        anchor = t.full_name.replace('.', '').lower()
        lines.append(f'| [`{t.full_name}`](#{anchor}) | {kind} | {dtid} | {size} | `0x{t.get_data_type_signature():016x}` |')
    for t in types:
        rel = os.path.relpath(t.source_file, os.path.join(os.path.dirname(OUT), '..'))
        lines += ['', f'## {t.full_name}', '', f'Source: [`{rel}`](../{rel})', '', '```', t.source_text.strip('\n'), '```']
    return '\n'.join(lines) + '\n'


def main():
    text = render(validate.load())
    if '--check' in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ''
        if current != text:
            print('docs/types.md is out of date: run python3 tools/gen_docs.py')
            return 1
        print('docs/types.md is up to date')
        return 0
    with open(OUT, 'w') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
